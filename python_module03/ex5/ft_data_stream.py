def return_best_player(Players: list) -> dict:
    """A simple function that will iterat throught the Players list
    and return the player with biggest level

    Args:
        Players (list): All Players on the server

    Returns:
        dict: the best player
    """
    best_player = None
    for player in Players:
        if (best_player is None or player["level"] > best_player["level"]):
            best_player = player
    return (best_player)


