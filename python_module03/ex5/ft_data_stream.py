def is_prime(num: int) -> bool:
    """return True if the given number is a prime number
    or False if it's not

    Args:
        num (int): number to test

    Returns:
        bool: True if prime, False if not
    """
    for i in range(2, num):
        if (num % i == 0):
            return (False)
    return (True)


def fibonacci_generator():
    """A generator that will generate the fibonaci sequence

    Yields:
        int: the ncall number on the fibonaci sequence
    """
    a = 0
    b = 1
    while True:
        yield a
        a, b = b, a + b


def prime_number_gen():
    """A generator that will return prime number

    Yields:
        int: the ncall prime number
    """
    a = 2
    while True:
        if (is_prime(a) is True):
            yield a
        a += 1


def fibonacci(num: int) -> None:
    """A function that will display the
    'num' number of the fibonacci sequence

    Args:
        num (int): n number of the sequence
    """
    string = ""
    gen = fibonacci_generator()
    for k in range(10):
        string += f" {next(gen)},"
    print(f"Fibonacci sequence (first {num}):{string}")


def prime_number(num: int):
    """A function that will display the
    'num' first prime number

    Args:
        num (int): n first prime number
    """
    string = ""
    gen = prime_number_gen()
    for k in range(num):
        string += f" {next(gen)},"
    print(f"Prime numbers (first {num}):{string}")


