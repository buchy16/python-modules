def generate_events(Players: list, event_number: int):
    """A generator that will generate random event by picking randomly
    a name on the players list and an event on the event list
    The generator will also attribut the right quantity of xp
    (given by the event selected) to the player selected
    if a player level up, the leveled up event will be send too

    Args:
        Players (list): All players on the server
        event_number (int): how many event we want

    Yields:
        tuple: the player and the event selected
    """
    k = 0
    while k < event_number:
        player, event = (Players[random.randint(0, len(Players) - 1)],
                         Events[random.randint(0, len(Events) - 1)])
        yield player, event
        player["xp"] += event["xp_value"]
        if (player["xp"] >= 500):
            while (player["xp"] >= 500):
                player["level"] += 1
                player["xp"] = player["xp"] - 500
            k += 1
            event = {"id": 11, "event_name": "leveled up", "xp_value": 0}
            yield player, event
        k += 1


def events_manager(Players: list, event_number: int, bool: bool) -> None:
    """A function that will trigger and analyse all the events
    generated by the function generate_events, it also call the function
    stream_analytics to display some event state like the number of events that
    occured, the number of treasur event and the number of leveled up event

    Args:
        Players (list): all the players on the server
        event_number (int): how many events you want
        bool (bool): True if you want to see only
                     the first three line of events
    """
    total_event_count = 0
    treasur_event = 0
    level_up_event = 0

    print(f"Processing {event_number} game events...\n")
    for player, event in generate_events(Players, event_number):
        if (bool is False or total_event_count < 3):
            print(f"Event {total_event_count + 1}: Player {player['name']} \
({player['level']}) {event['event_name']}")
        if (bool is True and total_event_count == 3):
            print("...")
        total_event_count += 1
        if (event["event_name"] == "found treasure" or
                event["event_name"] == "found rare treasure"):
            treasur_event += 1
        if (event["event_name"] == "leveled up"):
            level_up_event += 1
    stream_analytics(Players, total_event_count, treasur_event, level_up_event)


